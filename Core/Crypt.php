<?php

namespace Core;

use Exception;

/**
 * ============================================================================
 * Srin Engine - High-Performance Authenticated Encryption (AEAD)
 * ============================================================================
 * Developed by Arindam Makar
 * 
 * Provides military-grade, lightweight symmetric encryption using AES-256-GCM.
 * Features:
 *   - Hardware-accelerated AES-256 in Galois/Counter Mode (GCM)
 *   - Authenticated Encryption with Associated Data (AEAD) 128-bit authentication tag
 *   - Cryptographically secure 96-bit (12-byte) initialization vector (IV) per payload
 *   - Tamper-evident ciphertext verification (detects corruption and bit-flipping)
 *   - URL-safe, database-friendly Base64 serialization
 * ============================================================================
 */
class Crypt
{
    /**
     * Primary cipher algorithm (Galois/Counter Mode).
     */
    protected const CIPHER = 'aes-256-gcm';

    /**
     * AEAD authentication tag length (128-bit / 16 bytes).
     */
    protected const TAG_LENGTH = 16;

    /**
     * Standard GCM initialization vector length (96-bit / 12 bytes).
     */
    protected const IV_LENGTH = 12;

    /**
     * Resolve the 256-bit binary encryption key.
     *
     * @param string|null $key Custom key or null to resolve from config/env
     * @return string Exactly 32 binary bytes
     * @throws Exception If no encryption key is configured
     */
    public static function getKey(?string $key = null): string
    {
        $rawKey = $key;
        if (empty($rawKey)) {
            $rawKey = function_exists('config') ? (string) config('app.key', '') : '';
        }
        if (empty($rawKey)) {
            $rawKey = function_exists('env') ? (string) env('APP_KEY', '') : '';
        }
        if (empty($rawKey) && class_exists('\\Core\\App')) {
            \Core\App::loadEnv();
            $rawKey = function_exists('config') ? (string) config('app.key', '') : '';
            if (empty($rawKey)) {
                $rawKey = function_exists('env') ? (string) env('APP_KEY', '') : '';
            }
        }

        if (empty($rawKey)) {
            throw new Exception("Application encryption key is not set. Please set APP_KEY in your .env or Config/app.php file.");
        }

        // Support base64: prefix if generated via 'php srin key:generate'
        if (str_starts_with($rawKey, 'base64:')) {
            $decoded = base64_decode(substr($rawKey, 7), true);
            if ($decoded === false || strlen($decoded) < 32) {
                throw new Exception('Invalid base64 encryption key; key must decode to at least 32 bytes.');
            }
            return substr($decoded, 0, 32);
        }

        // Derive deterministic 32-byte binary key via SHA-256 for passphrase keys only
        return hash('sha256', $rawKey, true);
    }

    /**
     * Encrypt a plain-text string using AES-256-GCM authenticated encryption.
     *
     * @param string      $value The plain-text value to encrypt
     * @param string|null $key   Optional custom encryption key
     * @return string URL-safe Base64 encrypted payload
     * @throws Exception If OpenSSL encryption fails
     */
    public static function encrypt(string $value, ?string $key = null): string
    {
        $derivedKey = self::getKey($key);
        $iv = random_bytes(self::IV_LENGTH);
        $tag = '';

        $ciphertext = openssl_encrypt(
            $value,
            self::CIPHER,
            $derivedKey,
            OPENSSL_RAW_DATA,
            $iv,
            $tag,
            '',
            self::TAG_LENGTH
        );

        if ($ciphertext === false) {
            throw new Exception('AES-256-GCM encryption failed: ' . openssl_error_string());
        }

        // Pack: IV (12 bytes) + TAG (16 bytes) + CIPHERTEXT
        return rtrim(strtr(base64_encode($iv . $tag . $ciphertext), '+/', '-_'), '=');
    }

    /**
     * Decrypt an AES-256-GCM authenticated payload.
     *
     * @param string      $payload URL-safe Base64 payload generated by encrypt()
     * @param string|null $key     Optional custom key used during encryption
     * @return string|null Decrypted plain-text, or null if invalid or tampered
     */
    public static function decrypt(string $payload, ?string $key = null): ?string
    {
        if (empty($payload)) {
            return null;
        }

        $derivedKey = self::getKey($key);

        $decoded = base64_decode(strtr($payload, '-_', '+/'), true);
        if ($decoded === false || strlen($decoded) < (self::IV_LENGTH + self::TAG_LENGTH)) {
            return null;
        }

        $iv = substr($decoded, 0, self::IV_LENGTH);
        $tag = substr($decoded, self::IV_LENGTH, self::TAG_LENGTH);
        $ciphertext = substr($decoded, self::IV_LENGTH + self::TAG_LENGTH);

        try {
            $plaintext = openssl_decrypt(
                $ciphertext,
                self::CIPHER,
                $derivedKey,
                OPENSSL_RAW_DATA,
                $iv,
                $tag
            );

            return $plaintext !== false ? $plaintext : null;
        } catch (\Throwable) {
            return null;
        }
    }

    /**
     * Generate a cryptographically secure random base64 encryption key (32 bytes).
     *
     * @return string Format: "base64:<base64_encoded_32_bytes>"
     */
    public static function generateKey(): string
    {
        return 'base64:' . base64_encode(random_bytes(32));
    }
}
